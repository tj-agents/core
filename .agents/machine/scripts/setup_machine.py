def run_steps(steps, context: Context, check_only: bool, out=sys.stdout, err=sys.stderr) -> int:
    print(f"main checkout: {context.checkout or 'none (checkout-based steps are skipped)'}", file=out)
    drift = False
    failed = False
    for step in steps:
        try:
            reason = step.skip(context)
            if reason:
                print(f"n/a    {step.name}: {reason}", file=out)
                continue
            pending = step.check(context)
            if not pending:
                print(f"ok     {step.name}", file=out)
                continue
            if check_only:
                drift = True
                for item in pending:
                    print(f"drift  {step.name}: {item}", file=out)
                continue
            for change in step.apply(context) or pending:
                print(f"apply  {step.name}: {change}", file=out)
        except Exception as error:  # noqa: BLE001
            print(f"failed {step.name}: {error}", file=err)
            failed = True
            if step.required:
                return 2
    if failed:
        return 2
    return 1 if drift else 0


def machine_context() -> Context:
    home = Path.home()
    windows = os.name == "nt"
    return Context(
        home=home,
        checkout=main_checkout(Path(__file__).resolve().parent),
        environ=dict(os.environ),
        windows=windows,
        documents=documents_directory(home) if windows else None,
        user_environment=WindowsUserEnvironment() if windows else None,
    )


def main(argv: list[str] | None = None) -> int:
    if sys.version_info < (3, 11):
        print("setup_machine requires Python 3.11 or newer", file=sys.stderr)
        return 2
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="report drift, write nothing, exit 1 on drift")
    arguments = parser.parse_args(argv)
    return run_steps(STEPS, machine_context(), arguments.check)


if __name__ == "__main__":
    raise SystemExit(main())
