def permission_sync(context: Context):
    candidates = [context.script_directory.parent / "utility" / "plugin-selection" / "scripts"]
    if context.checkout is not None:
        candidates.append(context.checkout / ".agents" / "machine" / "utility" / "plugin-selection" / "scripts")
    for directory in candidates:
        path = directory / "harness_permissions_sync.py"
        if path.is_file():
            if str(directory) not in sys.path:
                sys.path.insert(0, str(directory))
            spec = importlib.util.spec_from_file_location("tj_agents_harness_permissions_sync", path)
            module = importlib.util.module_from_spec(spec)
            spec.loader.exec_module(module)
            return module
    raise SetupError("harness_permissions_sync.py is not available beside setup or in the main checkout")


def permissions_environment(context: Context) -> dict:
    return {**context.environ, "CLAUDE_CONFIG_DIR": str(context.claude_home), "CODEX_HOME": str(context.codex_home),
            "AGENT_STATE_DIRECTORY": str(context.state_directory)}


def synchronize_permissions(context: Context, mode: str) -> list[str]:
    changes, warnings = permission_sync(context).synchronize(permissions_environment(context), mode)
    for warning in warnings:
        print(f"warning harness permissions: {warning}", file=sys.stderr)
    return changes


def parse_table_header(line: str) -> tuple[bool, list[str]] | None:
    text = line.strip()
    if not text.startswith("["):
        return None
    array = text.startswith("[[")
    index = 2 if array else 1
    parts = []
    while True:
        while index < len(text) and text[index] in " \t":
            index += 1
        if index >= len(text):
            return None
        character = text[index]
        if character == '"':
            finish = index + 1
            while finish < len(text) and text[finish] != '"':
                finish += 2 if text[finish] == "\\" else 1
            if finish >= len(text):
                return None
            try:
                parts.append(json.loads(text[index:finish + 1]))
            except ValueError:
                return None
            index = finish + 1
        elif character == "'":
            finish = text.find("'", index + 1)
            if finish < 0:
                return None
            parts.append(text[index + 1:finish])
            index = finish + 1
        else:
            match = re.compile(r"[A-Za-z0-9_-]+").match(text, index)
            if not match:
                return None
            parts.append(match.group())
            index = match.end()
        while index < len(text) and text[index] in " \t":
            index += 1
        if text.startswith(".", index):
            index += 1
            continue
        closing = "]]" if array else "]"
        if not text.startswith(closing, index):
            return None
        rest = text[index + len(closing):].strip()
        return (array, parts) if not rest or rest.startswith("#") else None


def value_state(text: str, depth: int, multiline: str | None) -> tuple[int, str | None]:
    index = 0
    while index < len(text):
        if multiline:
            finish = text.find(multiline, index)
            if finish < 0:
                return depth, multiline
            index = finish + 3
            multiline = None
            continue
        if text.startswith('"""', index) or text.startswith("'''", index):
            multiline = text[index:index + 3]
            index += 3
            continue
        character = text[index]
        if character == "#":
            break
        if character == '"':
            index += 1
            while index < len(text) and text[index] != '"':
                index += 2 if text[index] == "\\" else 1
        elif character == "'":
            finish = text.find("'", index + 1)
            index = len(text) if finish < 0 else finish
        elif character in "[{":
            depth += 1
        elif character in "]}":
            depth -= 1
        index += 1
    return depth, multiline


def toml_sections(lines: list[str]) -> list[tuple[int, list[str] | None]]:
    sections: list[tuple[int, list[str] | None]] = [(0, None)]
    depth, multiline = 0, None
    for number, line in enumerate(lines):
        if not multiline and depth <= 0:
            header = parse_table_header(line)
            if header is not None:
                array, parts = header
                sections.append((number, None if array else parts))
                continue
            _, _, value = line.partition("=")
            depth, multiline = value_state(value, 0, None)
        else:
            depth, multiline = value_state(line, depth, multiline)
    return sections


def legacy_table(parts: list[str] | None) -> bool:
    if not parts:
        return False
    if len(parts) == 3 and parts[:2] == ["hooks", "state"]:
        return LEGACY_HOOK_STATE in parts[2]
    if len(parts) == 2 and parts[0] == "projects":
        return re.split(r"[\\/]", parts[1].rstrip("\\/"))[-1].casefold() == LEGACY_PROJECT
    return False


def legacy_keys(document: dict) -> list[tuple[str, ...]]:
    found = []
    hooks = document.get("hooks")
    state = hooks.get("state") if isinstance(hooks, dict) else None
    if isinstance(state, dict):
        found += [("hooks", "state", key) for key in state if legacy_table(["hooks", "state", key])]
    projects = document.get("projects")
    if isinstance(projects, dict):
        found += [("projects", key) for key in projects if legacy_table(["projects", key])]
    return found


def table_name(parts: tuple[str, ...]) -> str:
    return ".".join([*parts[:-1], json.dumps(parts[-1], ensure_ascii=False)])


def pruned(value):
    if isinstance(value, dict):
        items = {key: pruned(item) for key, item in value.items()}
        return {key: item for key, item in items.items() if item != {}}
    return value


